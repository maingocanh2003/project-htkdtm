  id: string;
  sku: string;
  name: string;
  categoryId: Exclude<ProductCategoryId, 'all'>;
  supplierId: string;
  color: string;
  colorSwatch: string;
  shape: string;
  material: string;
  style: string;
  importCostUsd: number; // Giá nhập từ cơ sở SX trong nước (USD/SP)
